-- Initialize per-monitor workspace groups (swaysome's `exec swaysome
-- init 1` equivalent). Without this, anything that opens before the
-- first Win+N press lands on Hyprland's own default plain-numbered
-- workspace (1, 2, …) instead of the group-prefixed one (11.., 21..) and
-- becomes unreachable through any of the binds above — confirmed live: a
-- session-start window got stranded on plain workspace "1", invisible to
-- every Win+1..0 press ("workspaces are broken").
--
-- Run at both hyprland.start AND on every monitor.added: a cold boot's
-- physical displays can still be mode-negotiating when hyprland.start
-- fires, so hl.get_monitors() there can come back empty/incomplete and
-- silently no-op for whichever monitor wasn't ready yet — this only ever
-- showed up on a real cold boot, never during a `hyprctl reload` (monitors
-- already active by then), which is why it went unnoticed in testing.
-- Idempotent either way (re-focusing an already-correct group is harmless),
-- so no de-dup needed between the two triggers.
local function init_workspace_groups()
  for _, m in ipairs(hl.get_monitors()) do
    local g = MONITOR_GROUP[m.name]
    if g then
      hl.dispatch(hl.dsp.focus({ monitor = m.name }))
      hl.dispatch(hl.dsp.focus({ workspace = g * 10 + 1 }))
    end
  end
end
-- Control-room TV (DP-1): populate its dedicated workspace (31) with
-- htop/cava/Jellyfin/voice-control panes. Guarded on DP-1 actually being
-- connected (same monitor-not-ready-at-cold-boot concern as
-- init_workspace_groups above) — control-room-launch.sh itself is also
-- idempotent, so firing this from both triggers below is harmless.
local function launch_control_room()
  for _, m in ipairs(hl.get_monitors()) do
    if m.name == "DP-1" then
      -- TTS null-sink + loopback (control-room-voice.py's speech, and the
      -- only thing control-room-cava.sh's dedicated cava instance reacts
      -- to) must exist before the panes that depend on it start.
      hl.exec_cmd("~/.local/bin/control-room-audio-setup.sh")
      hl.exec_cmd("~/.local/bin/control-room-launch.sh")
      return
    end
  end
end

hl.on("monitor.added", init_workspace_groups)
hl.on("monitor.added", launch_control_room)

hl.on("hyprland.start", function ()
  init_workspace_groups()

  -- Hand the session environment to systemd user services (they need
  -- WAYLAND_DISPLAY to show GUI), then (re)start them with it — mirrors
  -- sway's autostart.conf. Restarting here guarantees they come up with the
  -- session environment; all four units are also WantedBy=graphical-session
  -- .target and Restart=on-failure.
  hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY DISPLAY XDG_CURRENT_DESKTOP XDG_SESSION_TYPE; dbus-update-activation-environment --systemd WAYLAND_DISPLAY DISPLAY XDG_CURRENT_DESKTOP; systemctl --user restart elephant walker armoji-spotlight armoji-dock armoji-osd")

  hl.exec_cmd("~/.local/bin/theme.sh startup")
  hl.exec_cmd("swaync")
  hl.exec_cmd("hypridle")
  hl.exec_cmd("hyprsunset")
  hl.exec_cmd("~/.local/bin/bluelight-watch.sh")
  hl.exec_cmd("~/.config/waybar/scripts/bluelight.sh startup")
  -- case RGB off 21:00-05:00 (theme.sh apply_rgb/rgb-recheck)
  hl.exec_cmd("~/.local/bin/rgb-watch.sh")
  -- Caps Lock / Num Lock toggle notifications
  hl.exec_cmd("~/.local/bin/lock-watch.sh")
  -- Jump-to-window-on-urgent, with per-app exceptions (Viber toast auto-kill)
  hl.exec_cmd("~/.local/bin/activation-watch.sh")
  -- Low battery notifications (20/10/5%) — self-guards out on a desktop
  -- with no battery
  hl.exec_cmd("~/.local/bin/battery-watch.sh")
  hl.exec_cmd("waybar")

  launch_control_room()
end)
