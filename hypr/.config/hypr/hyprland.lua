------------------------------------------------
---- PER-MONITOR WORKSPACES (swaysome-alike) ----
------------------------------------------------
-- Hyprland has no native "workspace N per monitor" selector (verified live:
-- the "m~N" syntax used in Noctalia's leftover config does NOT actually
-- switch workspaces on this Hyprland version — only "m+1"/"m-1" relative
-- stepping works). Reimplemented by hand instead, replicating swaysome's own
-- numbering exactly: group digit (1 = DP-2 main monitor, 2 = HDMI-A-2 side)
-- concatenated with the pressed digit — "11".."19","110" / "21".."29","210".
local MONITOR_GROUP = { ["DP-2"] = 1, ["HDMI-A-2"] = 2, ["DP-1"] = 3 }

-- clear the base config's global-workspace binds on the same keys (see the
-- additive-binds note above the KEYBINDS section)
for i = 1, 10 do
    local key = i % 10
    hl.unbind(mod .. " + " .. key)
    hl.unbind(mod .. " + SHIFT + " .. key)
end

local function group_ws(n)
    local mon = hl.get_active_monitor()
    local g = (mon and MONITOR_GROUP[mon.name]) or 1
    return tonumber(tostring(g) .. tostring(n))
end

for i = 1, 10 do
    local key = i % 10
    -- Switch to workspace N on the focused monitor only
    hl.bind(mod .. " + " .. key, function()
        hl.dispatch(hl.dsp.focus({ workspace = group_ws(i) }))
    end)
    -- Move focused window to workspace N on its monitor, and follow
    hl.bind(mod .. " + SHIFT + " .. key, function()
        local t = group_ws(i)
        hl.dispatch(hl.dsp.window.move({ workspace = t }))
        hl.dispatch(hl.dsp.focus({ workspace = t }))
    end)
    -- Move EVERYTHING on the current workspace to workspace N (same
    -- monitor), and follow — move-workspace.sh equivalent
    hl.bind(mod .. " + ALT + " .. key, function()
        local cur = hl.get_active_workspace()
        if not cur then return end
        local t = group_ws(i)
        for _, w in ipairs(hl.get_workspace_windows(cur.id)) do
            hl.dispatch(hl.dsp.window.move({ window = "address:" .. w.address, workspace = t }))
        end
        hl.dispatch(hl.dsp.focus({ workspace = t }))
    end)
end

