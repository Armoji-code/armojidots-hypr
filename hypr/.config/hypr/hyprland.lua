-- Layer-shell blur (waybar, the custom GTK4 daemons' glass pills). This
-- USED TO be unnecessary — global decoration.blur.enabled alone was
-- confirmed live to reach layer surfaces too, no per-layer rule needed —
-- but that stopped being true at some point (likely a Hyprland update
-- changing layer-blur inheritance) and none of these had blur any more.
-- HL.LayerRuleSpec has its own explicit `blur` field now; every glass
-- surface needs an opt-in rule.
-- ignore_alpha is required too, not optional: without it blur covers the
-- layer's whole RECTANGULAR bounds regardless of the pill's own rounding —
-- confirmed live as "one big line of blur" with square corners on waybar,
-- spotlight, and the OSD. ignore_alpha skips blurring pixels at/below that
-- opacity, which is everywhere outside the actual rounded pill shape GTK
-- draws (the rest of the surface is fully transparent), so blur ends up
-- naturally clipped to the pill.
hl.layer_rule({ name = "waybar-blur", match = { namespace = "waybar" }, blur = true, ignore_alpha = 0.5 })
hl.layer_rule({ name = "armoji-osd-blur", match = { namespace = "armoji-osd" }, blur = true, ignore_alpha = 0.5 })
hl.layer_rule({ name = "armoji-dock-blur", match = { namespace = "armoji-dock" }, blur = true, ignore_alpha = 0.5 })
hl.layer_rule({ name = "spotlight-search-blur", match = { namespace = "spotlight-search" }, blur = true, ignore_alpha = 0.5 })
